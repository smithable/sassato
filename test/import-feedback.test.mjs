function as(s,actor,fn){const old=s.actor;s.actor=actor;try{return fn();}finally{s.actor=old;}}
function imported(f,options){const plan=previewImport(f.s,options);return applyImport(f.s,options,plan.digest);}
// Seed the old importer format exactly: version 1 task, raw provenance, a single imported
// event and autogenerated Human blocker/question. This is fixture data, never the live DB.
function legacy(f,{source,body,line,key,owner='a',status='blocked',humanOnly=false,waitingOn='human',warnings=['Status or dependency needs reconciliation']}) {
  const s=f.s,raw=readFileSync(source,'utf8'),digest=hash(raw),at='2026-11-09T11:00:00.000Z',sourceKey=`${source}#${key}`;
  s.run('INSERT OR IGNORE INTO imports(workspace_id,path,digest,raw,created_at) VALUES(?,?,?,?,?)',s.ws,source,digest,raw,at);
  const title=body.replace(/^#+\s*/,'').split('\n')[0].slice(0,180),savedBody=`${body}\n\nImported from ${source}:${line}\nSource digest: ${digest}`;
  const id=s.run('INSERT INTO tasks(workspace_id,title,body,owner,status,human_only,for_role,creator,created_at,updated_at,completed_at) VALUES(?,?,?,?,?,?,?,?,?,?,?)',s.ws,title,savedBody,owner,status,humanOnly?1:0,humanOnly?'human':null,'human',at,at,status==='done'?at:null).lastInsertRowid;
  const itemDigest=hash(JSON.stringify({body,owner,status,kind:'task',warnings}));
  s.run('INSERT INTO import_items(workspace_id,source_key,digest,task_id) VALUES(?,?,?,?)',s.ws,sourceKey,itemDigest,id);
  s.event('task',`T${id}`,'imported',{source,line,source_key:sourceKey,warnings});s.index('task',`T${id}`,title,savedBody,{role:owner,status});
  let questionId,blockerId;
  if(status==='blocked') {
    blockerId=s.run('INSERT INTO blockers(workspace_id,task_id,kind,waiting_on,body,created_by,created_at) VALUES(?,?,?,?,?,?,?)',s.ws,id,'human',waitingOn,warnings.join('; ')||'Reconcile imported item','human',at).lastInsertRowid;
    if(humanOnly)questionId=s.run('INSERT INTO questions(workspace_id,task_id,blocker_id,asked_by,question,created_at) VALUES(?,?,?,?,?,?)',s.ws,id,blockerId,'human',`Review this imported action and record the remaining decision. Existing answers are preserved in the task body.\n\n${title}`,at).lastInsertRowid;
  }
  return {id:`T${id}`,body:savedBody,blockerId,questionId};
}

