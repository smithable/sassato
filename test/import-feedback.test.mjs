function legacyWip(f,{source,role='lead',line=1,body}) {
  const raw=readFileSync(source,'utf8'),at='2026-11-09T11:00:00.000Z',sourceKey=`${source}#wip/${role}`;
  f.s.run('INSERT OR IGNORE INTO imports(workspace_id,path,digest,raw,created_at) VALUES(?,?,?,?,?)',f.s.ws,source,hash(raw),raw,at);
  const notes=`Imported newest stopped entry from ${source}:${line}. Source history remains in the import record.`;
  f.s.run('INSERT INTO wip(workspace_id,role,current,next,notes,updated_at) VALUES(?,?,?,?,?,?)',f.s.ws,role,body,'',notes,at);
  f.s.run('INSERT INTO import_items(workspace_id,source_key,digest) VALUES(?,?,?)',f.s.ws,sourceKey,hash(JSON.stringify({body,owner:role,status:'open',kind:'wip',warnings:[]})));
  f.s.event('wip',role,'imported',{source,line,source_key:sourceKey});
  return f.s.get('SELECT * FROM wip WHERE workspace_id=? AND role=?',f.s.ws,role);
}

